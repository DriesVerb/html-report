import test, { describe, it } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const runtimePath = path.resolve(__dirname, "../skills/html-report/assets/report-runtime.js");
const shellPath = path.resolve(__dirname, "../skills/html-report/assets/template-shell.html");

const runtime = await import(runtimePath);
const {
  DAISYUI_THEMES,
  cssColorToHexAndRgba,
  sanitizeMermaidSource,
  renderMermaidWithTheme,
  initThemeDropdown,
  checkInsufficientHorizontalSpace
} = runtime.default || runtime;

describe("Phase 1: Runtime Assets & Template Shell Unit Tests", () => {
  describe("template-shell.html integrity", () => {
    it("should exist and contain all 5 required template slots", () => {
      assert.ok(fs.existsSync(shellPath), "template-shell.html must exist on disk");
      const shell = fs.readFileSync(shellPath, "utf-8");

      assert.ok(shell.includes("<!-- {{TITLE}} -->"), "Missing TITLE slot");
      assert.ok(shell.includes("<!-- {{FAVICON}} -->"), "Missing FAVICON slot");
      assert.ok(shell.includes("<!-- {{HEAD_EXTRAS}} -->"), "Missing HEAD_EXTRAS slot");
      assert.ok(shell.includes("<!-- {{CONTENT}} -->"), "Missing CONTENT slot");
      assert.ok(shell.includes("<!-- {{RUNTIME_SCRIPT}} -->"), "Missing RUNTIME_SCRIPT slot");
    });

    it("should include Core 4 CDNs and standard layout components", () => {
      const shell = fs.readFileSync(shellPath, "utf-8");
      assert.ok(shell.includes("daisyui"), "Must include DaisyUI CDN link");
      assert.ok(shell.includes("tailwindcss.com"), "Must include Tailwind CDN");
      assert.ok(shell.includes("lucide"), "Must include Lucide Icons CDN");
      assert.ok(shell.includes("alpinejs"), "Must include Alpine.js CDN");

      assert.ok(shell.includes('id="navbar-report-title"'), "Must include report title element");
      assert.ok(shell.includes('id="toc-dropdown"'), "Must include TOC dropdown");
      assert.ok(shell.includes('id="settings-dropdown"'), "Must include settings gear dropdown");
      assert.ok(shell.includes('id="settings-gear-btn"'), "Must include gear button");
      assert.ok(shell.includes('id="theme-swatch-list"'), "Must include theme picker inside gear panel");
      assert.ok(shell.includes('id="download-dropdown-menu"'), "Must include export actions in gear panel");
      assert.ok(shell.includes('id="download-html-btn"'), "Must include download HTML button");
      assert.ok(shell.includes('id="download-pdf-btn"'), "Must include download PDF button");
      assert.ok(shell.includes('id="pdf-not-ready-modal"'), "Must include interactive PDF warning modal");
      assert.ok(shell.includes("<footer"), "Must include footer");
      assert.ok(shell.includes("generated by"), "Must include generated by text");
    });

    it("should include DaisyUI badge anti-wrapping safeguard in global CSS", () => {
      const shell = fs.readFileSync(shellPath, "utf-8");
      assert.ok(shell.includes(".badge {"), "Must define .badge rule");
      assert.ok(shell.includes("white-space: nowrap !important;"), "Must enforce white-space: nowrap !important on .badge");
      assert.ok(shell.includes("flex-shrink: 0;"), "Must enforce flex-shrink: 0 on .badge");
    });

    it("should allow WebSocket and HTTP/HTTPS connections in CSP for live SSE streaming", () => {
      const shell = fs.readFileSync(shellPath, "utf-8");
      assert.ok(
        shell.includes("connect-src 'self' ws: wss: http: https:;"),
        "CSP connect-src must allow ws:, wss:, http:, and https: for live SSE and WebSockets"
      );
    });
  });

  describe("report-runtime.js: DAISYUI_THEMES catalog", () => {
    it("should contain all 32 standard DaisyUI themes with light defaulting first", () => {
      assert.equal(DAISYUI_THEMES.length, 32);
      assert.equal(DAISYUI_THEMES[0], "light");
      assert.ok(DAISYUI_THEMES.includes("dark"));
      assert.ok(DAISYUI_THEMES.includes("cupcake"));
      assert.ok(DAISYUI_THEMES.includes("synthwave"));
      assert.ok(DAISYUI_THEMES.includes("nord"));
      assert.ok(DAISYUI_THEMES.includes("sunset"));
    });
  });

  describe("report-runtime.js: canvas 2D color resolution", () => {
    it("should convert simulated canvas 2D pixel data into exact hex and rgba strings", () => {
      const mockCtx = {
        fillStyle: "",
        fillRect: () => {},
        getImageData: () => ({
          data: new Uint8ClampedArray([255, 87, 34, 255])
        })
      };

      const result = cssColorToHexAndRgba("oklch(0.65 0.24 35)", mockCtx);
      assert.equal(result.hex, "#ff5722");
      assert.equal(result.r, 255);
      assert.equal(result.g, 87);
      assert.equal(result.b, 34);
      assert.equal(result.a, 1);
      assert.equal(result.rgba(0.5), "rgba(255, 87, 34, 0.5)");
    });

    it("should fallback gracefully when canvas context is unavailable", () => {
      const fallback = cssColorToHexAndRgba(null, null);
      assert.equal(fallback.hex, "#3b82f6");
      assert.equal(fallback.rgba(1), "rgba(59, 130, 246, 1)");
    });
  });

  describe("report-runtime.js: Mermaid list syntax defense", () => {
    it("should sanitize numbered list tokens in subgraph titles", () => {
      const raw = `subgraph sub1 ["1. Architecture Pipeline"]
  nodeA["Step A"]
end`;
      const sanitized = sanitizeMermaidSource(raw);
      assert.ok(sanitized.includes('subgraph sub1 ["Step 1 - Architecture Pipeline"]'));
      assert.ok(!sanitized.includes('["1. Architecture Pipeline"]'));
    });

    it("should sanitize numbered list tokens in bracketed node titles", () => {
      const raw = `graph TD\nA["1. Initialize Pipeline"] --> B["2. Run Verification"]`;
      const sanitized = sanitizeMermaidSource(raw);
      assert.ok(sanitized.includes('A["Step 1 - Initialize Pipeline"]'));
      assert.ok(sanitized.includes('B["Step 2 - Run Verification"]'));
    });

    it("should leave valid diagrams without numbered lists untouched", () => {
      const valid = `flowchart LR\nA[Start] --> B[Process] --> C[End]`;
      assert.equal(sanitizeMermaidSource(valid), valid);
    });

    it("should assign raw source via textContent to prevent HTML tag corruption", async () => {
      let runCalled = false;
      const mockNode = {
        dataset: {},
        textContent: `flowchart LR\nA["LLM"] -->|"Emits <main> Fragment"| B["CLI"]`,
        attributes: {},
        removeAttribute: () => {},
        getAttribute: (k) => mockNode.attributes[k]
      };

      const originalDoc = globalThis.document;
      const originalWindow = globalThis.window;
      globalThis.document = {
        querySelectorAll: (sel) => (sel === ".mermaid" ? [mockNode] : [])
      };
      globalThis.window = {
        mermaid: {
          initialize: () => {},
          run: async () => { runCalled = true; }
        }
      };

      try {
        await renderMermaidWithTheme({});
        assert.ok(runCalled, "window.mermaid.run should be called");
        assert.ok(mockNode.textContent.includes("<main>"), "textContent should preserve text without HTML tag parse");
        assert.equal(mockNode.dataset.mermaidSource, `flowchart LR\nA["LLM"] -->|"Emits <main> Fragment"| B["CLI"]`);
      } finally {
        globalThis.document = originalDoc;
        globalThis.window = originalWindow;
      }
    });
  });

  describe("report-runtime.js: theme swatch list builder (DOM Mock)", () => {
    it("should populate 32 theme items with preview swatches", () => {
      const appendedChildren = [];
      const mockListEl = {
        innerHTML: "",
        appendChild: (child) => appendedChildren.push(child)
      };

      // Mock DOM globals
      const originalDoc = globalThis.document;
      globalThis.document = {
        documentElement: {
          getAttribute: () => "light"
        },
        getElementById: (id) => (id === "theme-swatch-list" ? mockListEl : null),
        createElement: (tag) => {
          return {
            tagName: tag,
            attributes: {},
            setAttribute(k, v) { this.attributes[k] = v; },
            getAttribute(k) { return this.attributes[k]; },
            addEventListener() {},
            innerHTML: "",
            className: ""
          };
        }
      };

      try {
        initThemeDropdown();
        assert.ok(appendedChildren.length >= 32);
        assert.equal(appendedChildren[0].getAttribute("data-theme"), "light");
        assert.ok(appendedChildren[0].innerHTML.includes("data-swatch-preview=\"light\""));
      } finally {
        globalThis.document = originalDoc;
      }
    });

    it("should register custom themes and include them in swatch dropdown with custom indicator", () => {
      const { registerCustomTheme, DAISYUI_THEMES } = runtime;
      const appendedChildren = [];
      const mockListEl = {
        innerHTML: "",
        appendChild: (child) => appendedChildren.push(child)
      };

      const originalDoc = globalThis.document;
      globalThis.document = {
        head: {
          appendChild() {}
        },
        documentElement: {
          getAttribute: () => "light"
        },
        getElementById: (id) => (id === "theme-swatch-list" ? mockListEl : null),
        createElement: (tag) => {
          return {
            tagName: tag,
            attributes: {},
            setAttribute(k, v) { this.attributes[k] = v; },
            getAttribute(k) { return this.attributes[k]; },
            addEventListener() {},
            innerHTML: "",
            className: ""
          };
        }
      };

      try {
        registerCustomTheme("test-brand-theme", "[data-theme=\"test-brand-theme\"] { --p: 60% 0.2 250; }");
        assert.ok(DAISYUI_THEMES.includes("test-brand-theme"));

        initThemeDropdown();
        const customItem = appendedChildren.find((el) => el.getAttribute("data-theme") === "test-brand-theme");
        assert.ok(customItem, "Custom theme button must be rendered in dropdown");
        assert.ok(customItem.innerHTML.includes("custom"), "Must include custom badge indicator");
      } finally {
        globalThis.document = originalDoc;
      }
    });
  });

  describe("report-runtime.js: Datastar live runtime & signals", () => {
    it("should rehydrate Lucide icons when rehydrateLucideIcons is called", () => {
      const { rehydrateLucideIcons } = runtime;
      let lucideCalled = false;
      const originalWindow = globalThis.window;
      globalThis.window = {
        lucide: {
          createIcons: () => {
            lucideCalled = true;
          }
        }
      };

      try {
        rehydrateLucideIcons();
        assert.equal(lucideCalled, true, "lucide.createIcons must be called");
      } finally {
        globalThis.window = originalWindow;
      }
    });

    it("should synchronize DaisyUI theme selection with Datastar $theme signal", () => {
      const { syncDatastarTheme } = runtime;
      let dispatchedEvent = null;
      let datastarMergedTheme = null;

      const originalWindow = globalThis.window;
      const originalDoc = globalThis.document;

      globalThis.window = {
        datastar: {
          mergeSignals: (signals) => {
            datastarMergedTheme = signals.theme;
          }
        }
      };

      const mockElement = {
        _dsSignals: { theme: "light" }
      };

      globalThis.document = {
        dispatchEvent: (evt) => {
          dispatchedEvent = evt;
        },
        querySelectorAll: (selector) => {
          if (selector === "[data-signals]") return [mockElement];
          return [];
        }
      };

      try {
        syncDatastarTheme("dracula");
        assert.ok(dispatchedEvent, "Must dispatch custom event");
        assert.equal(dispatchedEvent.type, "datastar-merge-signals");
        assert.equal(dispatchedEvent.detail.theme, "dracula");
        assert.equal(datastarMergedTheme, "dracula");
        assert.equal(mockElement._dsSignals.theme, "dracula");
      } finally {
        globalThis.window = originalWindow;
        globalThis.document = originalDoc;
      }
    });
  });
});
